import { type EquipmentType, type ExerciseDefinition } from '@ferrum/domain';
import { type ApparatusKind, type ImplementKind } from './shapes.ts';
import { type PoseSpec, type View } from './rig.ts';

export type AnchorKind =
  | 'hands'
  | 'near-hand'
  | 'hips'
  | 'ankles'
  | 'near-ankle'
  | 'knees'
  | 'toes'
  | 'chest'
  | 'upper-back';

export interface AnimationSpec {
  readonly view: View;
  readonly apparatus: readonly ApparatusKind[];
  // 'auto' takes the implement from the exercise's equipment type, so one authored pose
  // serves the barbell, dumbbell and machine versions of the same movement.
  readonly implement: ImplementKind | 'auto';
  readonly anchor: AnchorKind;
  // In a bodyweight movement the hands are bolted to a bar and the body is what travels,
  // so the bar path has to be sampled somewhere other than the implement.
  readonly trace?: AnchorKind;
  readonly start: PoseSpec;
  readonly finish: PoseSpec;
  readonly durationMs: number;
  readonly cue: string;
}

