export function resolveAnimation(definition: ExerciseDefinition): AnimationSpec {
  // No silent fallback: a movement family added to the library without a pose must fail
  // loudly in the coverage test, not quietly render somebody else's exercise.
  const base = BY_MOVEMENT[definition.movementId];
  if (base === undefined) {
    throw new Error(`No base animation for movement "${definition.movementId}"`);
  }
  const merged: AnimationSpec = { ...base, ...BY_EXERCISE[definition.id] };
  return merged.implement === 'auto'
    ? { ...merged, implement: EQUIPMENT_IMPLEMENT[definition.equipmentType] }
    : merged;
}

export function animationMovementIds(): readonly string[] {
  return Object.keys(BY_MOVEMENT);
}
